import pandas as pd

movies = pd.DataFrame({
    'title': ['3 Idiots', 'Dangal', 'Sholay', 'PK', 'Lagaan', 'Taare Zameen Par'],
    'rating': [8.4, 8.3, 8.1, 8.1, 8.1, 8.3],
    'release_year': [2009, 2016, 1975, 2014, 2001, 2007]
})

result = movies.sort_values('rating', ascending=False)

print(result)

ipl = pd.DataFrame({
    'team': ['CSK', 'MI', 'RCB', 'KKR', 'GT'],
    'points': [16, 14, 18, 12, 16],
    'net_run_rate': [0.65, 0.45, 0.75, 0.30, 0.55]
})

result = ipl.sort_index(ascending=False)

print(result)

youtube = pd.DataFrame({
    'video_title': ['Music Video', 'Cricket Highlights', 'Comedy Video'],
    'views': [5000000, 3500000, 2000000],
    'likes': [450000, 300000, 180000]
}, index=[5, 8, 12])

result = youtube.reset_index(drop=True)

print(result)

zomato = pd.DataFrame({
    'restaurant': ['Swiggy Cafe', "McDonald's", "Domino's", 'Pizza Hut'],
    'rating': [4.1, 4.2, 4.5, 4.0]
}, index=['A', 'B', 'C', 'D'])

result = zomato.reindex(['C', 'A', 'B', 'D'])

print(result)

flipkart = pd.DataFrame({
    'product_name': ['Laptop', 'Mobile', 'Headphones', 'Smartwatch'],
    'price': [55000, 25000, 3000, 5000],
    'discount': [15, 25, 40, 30]
})

result = flipkart.sort_values('discount', ascending=False)
result = result.reset_index(drop=True)

print(result)

